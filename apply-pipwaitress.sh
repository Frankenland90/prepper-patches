#!/bin/bash
set -eEuo pipefail
# pipWaitress (commit45a, Schritt A vor perfWsgi commit45): waitress 3.0.2 ins venv des Dashboards installieren - offline aus dem eingebetteten Wheel.
# Aufruf: bash /tmp/apply-pipwaitress.sh commit45a [dry-run]
# - Wheel waitress-3.0.2-py3-none-any.whl (reines Python, keine Abhaengigkeiten) ist eingebettet; sha256 wie auf PyPI: c56d67fd6e87c2ee598b76abdd4e96cfad1f24cacdea5078d382b1f9d7b5ed2e
# - pip mit --no-index --no-deps --only-binary :all: --require-hashes (kein Netz, nichts anderes wird installiert oder aktualisiert)
# - laeuft als fmg, NIE als root/sudo (sonst root-eigene Dateien im venv); kein Dienst-Neustart, dashboard.py und alle anderen Dateien bleiben unberuehrt
# - idempotent: waitress 3.0.2 schon da -> nichts zu tun; andere waitress-Version -> STOP
# - ~ip (Rest eines alten pip-Laufs) wird nur gelesen und gemeldet, nicht angefasst
# Rueckweg: /home/fmg/prepper-dashboard/venv/bin/python -m pip uninstall -y waitress
COMMIT_ARG="${1:-unbekannt}"; MODE_ARG="${2:-}"
case "$MODE_ARG" in ""|dry-run|--dry-run|trockenlauf) ;; *) echo "STOP: unbekannter zweiter Parameter '$MODE_ARG' (erlaubt: dry-run) - nichts geaendert"; exit 1;; esac
DRY=0; [[ -n "$MODE_ARG" ]] && DRY=1
DASH_DIR="/home/fmg/prepper-dashboard"
VPY="$DASH_DIR/venv/bin/python"
WANT_V="3.0.2"
WHL_SHA="c56d67fd6e87c2ee598b76abdd4e96cfad1f24cacdea5078d382b1f9d7b5ed2e"
W=/tmp/pipwaitress-apply
stop() { echo "STOP: $1 - nichts geaendert"; exit 1; }
trap 'ec=$?; [[ $ec -ne 0 ]] && echo "ABBRUCH (Exit $ec) in Zeile $LINENO - waitress-Stand bitte mit: $VPY -m pip show waitress pruefen"' ERR
echo "=== pipWaitress ($COMMIT_ARG$([[ $DRY == 1 ]] && echo ", TROCKENLAUF")): waitress $WANT_V ins venv, offline, ohne Neustart ==="
[[ "$(id -u)" != 0 ]] || stop "bitte NICHT als root/sudo starten (sonst root-eigene Dateien im venv) - als fmg: bash /tmp/apply-pipwaitress.sh $COMMIT_ARG"
[[ -x "$VPY" ]] || stop "venv-Python $VPY fehlt"
PYV=$("$VPY" -c 'import sys; print("%d.%d" % sys.version_info[:2])')
"$VPY" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' || stop "venv-Python $PYV zu alt (waitress braucht >= 3.9)"
PIPV=$("$VPY" -m pip --version 2>/dev/null | cut -d' ' -f2) || true
[[ -n "$PIPV" ]] || stop "pip im venv nicht aufrufbar ($VPY -m pip)"
SP=$("$VPY" -c 'import sysconfig; print(sysconfig.get_paths()["purelib"])')
echo "OK venv: Python $PYV, pip $PIPV, site-packages $SP (Eigentuemer $(stat -c %U:%G "$SP"))"
[[ -w "$SP" ]] || stop "site-packages $SP fuer $(id -un) nicht beschreibbar"
case "$SP" in "$DASH_DIR"/venv/*) ;; *) stop "site-packages $SP liegt nicht im venv des Dashboards";; esac
# ~ip nur lesen
TIP=$(find "$SP" -maxdepth 1 -name '~*' -printf '%f (%u:%g)\n' 2>/dev/null || true)
if [[ -n "$TIP" ]]; then echo "HINWEIS Reste alter pip-Laeufe in site-packages (nur gemeldet, nicht angefasst):"; echo "$TIP" | sed 's/^/   /'; else echo "OK keine ~-Reste alter pip-Laeufe in site-packages"; fi
ROOTF=$(find "$SP" -maxdepth 1 -user root -printf '%f\n' 2>/dev/null | head -5 || true)
[[ -z "$ROOTF" ]] || echo "HINWEIS root-eigene Eintraege in site-packages (nur gemeldet): $(echo $ROOTF)"
[[ ! -e "$SP/waitress" || -w "$SP/waitress" ]] || stop "$SP/waitress existiert und ist nicht beschreibbar"
# Stand vorher
CURV=$("$VPY" -c 'import importlib.metadata as m
try:
    print(m.version("waitress"))
except m.PackageNotFoundError:
    print("")' 2>/dev/null || true)
D16=$(sha256sum "$DASH_DIR/dashboard.py" | cut -c1-16)
FREEZE0=$("$VPY" -m pip freeze --all 2>/dev/null | { grep -vi '^waitress==' || true; } | sha256sum | cut -c1-16)
if [[ "$CURV" == "$WANT_V" ]]; then
  "$VPY" -c 'import waitress, waitress.server' || stop "waitress $CURV laut pip da, aber Import scheitert"
  echo "OK waitress $CURV schon installiert ($("$VPY" -c 'import waitress, os; print(os.path.dirname(waitress.__file__))')) - nichts zu tun"
  echo "COMMIT $COMMIT_ARG pipwaitress=1 fertig (schon drin)"; exit 0
fi
[[ -z "$CURV" ]] || stop "waitress $CURV ist schon installiert, erwartet $WANT_V oder keins - bitte melden"
rm -rf "$W" && mkdir -p "$W"
base64 -d > "$W/waitress-3.0.2-py3-none-any.whl" <<'B64END'
